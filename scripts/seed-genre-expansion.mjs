async function main() {
  if (!process.env.DATABASE_URL) {
    console.error("DATABASE_URL not set in .env.local");
    process.exit(1);
  }
  const sql = neon(process.env.DATABASE_URL);

  let totalShort = 0;
  let totalLong = 0;
  let totalDiscarded = 0;
  let totalDuplicate = 0;

  for (const [genre, sentences] of Object.entries(GENRES)) {
    for (const raw of sentences) {
      const sanitized = sanitizeForTyping(raw);

      let mode;
      if (sanitized.length >= LONG_MIN_LENGTH) mode = "long";
      else if (sanitized.length >= SHORT_MIN_LENGTH) mode = "short";
      else {
        totalDiscarded += 1;
        console.log(`[폐기, ${sanitized.length}자] ${genre}: ${sanitized}`);
        continue;
      }

      const existing = await sql`
        SELECT id FROM typing_contents WHERE body = ${sanitized} LIMIT 1
      `;
      if (existing.length > 0) {
        totalDuplicate += 1;
        continue;
      }

      await sql`
        INSERT INTO typing_contents (mode, body, source, is_active)
        VALUES (${mode}, ${sanitized}, ${genre}, true)
      `;
      if (mode === "short") totalShort += 1;
      else totalLong += 1;
    }
  }

  console.log(`\n✓ 신규 등록: 단문 ${totalShort}행 / 장문 ${totalLong}행`);
  console.log(`  폐기(45자 미만): ${totalDiscarded}행, 중복 스킵: ${totalDuplicate}행`);
}

main().catch((err) => {
  console.error("시딩 실패:", err);
  process.exit(1);
});
